"""A12. Real examples for the paper (no LLM calls).

1. Repair example (replacement for the current repair-step figure): the first generation of the JWST bank of
   gemini-3.5-flash-lite (run, category order) that C2 does not rescue and C4 rescues with the fewest calls.
   Shown: the generated fragment around the diagnostic, the diagnostic and its router category, the C4 repaired
   fragment and the C2 final fragment.
2. Richness example: the same category and run generated by gpt-6-luna with the minimal prompt (C0) and with
   the guided prompt (E1), each cropped to about 15 lines: the first requirement and, where present, the first
   part, attribute, constraint/assert and satisfy lines. The category is the first one (input order) where the
   guided model has parts, constraints and satisfy relations and both models are valid.

Writes results/analysis/a12_paper_examples/{fig_repair_example.tex, fig_richness_example.tex, examples.md}.

    python -m evaluation.analysis.a12_paper_examples
"""

from __future__ import annotations

import re

import pandas as pd

from core.agents.agent2.logic import SysMLAgent
from core.config import RESULTS_DIR
from evaluation.analysis.common import jsonl, load_models, out_dir, write_md

CONTEXT = 3
ROUTER_LABELS = {"CONSTRAINT_EXPR": "Constraint expr.", "DECLARATION_FORM": "Declaration form",
                 "QUALIFICATION": "Qualification", "DELIMITERS": "Delimiters", "DOC_COMMENT": "Doc/Comment",
                 "LITERALS_STRINGS": "Literals/strings", "ALT_NO_VIABLE": "No viable alternative", "LEXER": "Lexer",
                 "UNKNOWN": "Unknown"}


def fragment(code: str, center: int, before: int = CONTEXT, after: int = CONTEXT) -> tuple[str, int]:
    lines = code.splitlines()
    lo, hi = max(0, center - 1 - before), min(len(lines), center + after)
    return "\n".join(lines[lo:hi]), lo + 1


def listing(code: str, first_line: int, caption: str) -> str:
    return (f"\\begin{{lstlisting}}[style=sysml,numbers=left,breaklines=true,firstnumber={first_line},title={{{caption}}}]\n"
            f"{code}\n\\end{{lstlisting}}")


def repair_example(out) -> tuple[str, str]:
    res = pd.read_csv(RESULTS_DIR / "jwst_v1_bank_flashlite" / "pipeline_results.csv")
    res = res[res.initial_errors > 0]
    w = res.pivot_table(index=["run", "category"], columns="condition", values=["converged", "llm_calls", "iterations"],
                        aggfunc="first")
    ok = w["converged"].astype(str) == "True"
    cand = w[(~ok["C2"]) & ok["C4"]].sort_values(("llm_calls", "C4"), kind="stable")
    run, category = cand.index[0]
    models = load_models("R9b")
    pick = lambda c: models[(models.condition == c) & (models.run == run) & (models.category == category)].iloc[0]  # noqa: E731
    gen = SysMLAgent.clean_sysml(pick("C4").generated_code)
    agent = SysMLAgent.__new__(SysMLAgent)
    from core.agents.agent2.error_router import ErrorRouter

    err = ErrorRouter().route_all(agent.validate_sysml(gen))[0]
    g_frag, g_first = fragment(gen, err["line"])
    c4 = pick("C4").sysml_code
    c2 = pick("C2").sysml_code
    c4_frag, c4_first = fragment(c4, err["line"])
    c2_frag, c2_first = fragment(c2, err["line"])
    reps = [r for r in jsonl(RESULTS_DIR / "jwst_v1_bank_flashlite" / "repairs.jsonl")
            if r["condition"] == "C2" and int(r["run"]) == int(run) and r["category"] == category]
    label = ROUTER_LABELS.get(err["category_id"], err["category_id"])
    caption = (f"Repair of a real generation of the out-of-sample JWST bank (gemini-3.5-flash-lite, category "
               f"``{category}'', run {run}). The parser fails at line {err['line']}, column {err['column']} "
               f"(\\texttt{{{err['error'].replace('_', chr(92) + '_').replace('{', chr(92) + '{').replace('}', chr(92) + '}')[:90]}}}); "
               f"the router assigns it to \\textit{{{label}}}. With the knowledge base of that category (C4) one "
               f"call fixes it; blind repair (C2) is still invalid after "
               f"{int(w.loc[(run, category), ('iterations', 'C2')])} iterations ({len(reps)} calls).")
    tex = ("\\begin{figure}[t]\n\\centering\n"
           + listing(g_frag, g_first, "Generated (invalid)") + "\n"
           + listing(c4_frag, c4_first, "Repaired, C4 (valid)") + "\n"
           + listing(c2_frag, c2_first, f"C2 after {int(w.loc[(run, category), ('iterations', 'C2')])} iterations (still invalid)") + "\n"
           + f"\\caption{{{caption}}}\n\\label{{fig:repair_example}}\n\\end{{figure}}\n")
    (out / "fig_repair_example.tex").write_text(tex, encoding="utf-8")
    md = (f"## Repair example (JWST bank, gemini-3.5-flash-lite, {category}, run {run})\n\n"
          f"Diagnostic: line {err['line']}, column {err['column']}: `{err['error']}`; router category "
          f"{err['category_id']}. C4: {int(w.loc[(run, category), ('llm_calls', 'C4')]) - 1} repair call(s); "
          f"C2: {len(reps)} calls, not rescued.\n\nGenerated:\n```\n{g_frag}\n```\nC4:\n```\n{c4_frag}\n```\n"
          f"C2 (final):\n```\n{c2_frag}\n```")
    return tex, md


def crop(code: str, max_lines: int = 16, block_lines: int = 6) -> str:
    """Whole blocks (by indentation, as the repair loop extracts them): the first requirement, the first part
    usage or definition with a body, and the first satisfy line; each block cut at `block_lines` lines,
    '...' marks omitted lines."""
    agent = SysMLAgent.__new__(SysMLAgent)
    lines = code.splitlines()
    picks: list[tuple[int, int]] = [(0, 1)]
    for pattern in (r"^\s*requirement\b", r"^\s*part\b.*\{", r"^\s*satisfy\b"):
        i = next((i for i, l in enumerate(lines) if re.search(pattern, l)), None)
        if i is None:
            continue
        n = len(agent._extract_block_by_indent(lines, i + 1).splitlines())
        picks.append((i, i + min(n, block_lines)))
    picks.append((len(lines) - 1, len(lines)))
    out, prev = [], -1
    for a, b in sorted(set(picks)):
        if a > prev + 1 and prev >= 0:
            out.append("    ...")
        out += lines[max(a, prev + 1):b]
        prev = max(prev, b - 1)
    return "\n".join(out[:max_lines])


def richness_example(out) -> tuple[str, str]:
    c0, e1 = load_models("E4"), load_models("E1")
    c0 = c0[c0.condition == "C1"]
    e1 = e1[(e1.condition == "C1") & (e1.llm == "gpt-6-luna")]
    m = c0.merge(e1, on=["run", "category"], suffixes=("_c0", "_e1"))
    has = lambda code, w: bool(re.search(rf"\b{w}\b", code))  # noqa: E731
    m = m[m.valid_c0.astype(bool) & m.valid_e1.astype(bool)
          & m.sysml_code_e1.map(lambda c: has(c, "part") and has(c, "constraint") and has(c, "satisfy"))]
    order = {c: i for i, c in enumerate(dict.fromkeys(load_models("E1").category))}
    m = m.assign(o=m.category.map(order)).sort_values(["o", "run"])
    r = m.iloc[0]
    a, b = crop(r.sysml_code_c0), crop(r.sysml_code_e1)
    caption = (f"The same category (``{r.category}'', run {r.run}) generated by gpt-6-luna with the minimal "
               f"prompt (C0, left) and with the grammar-guided prompt (E1, right); both are valid. Cropped to the "
               f"first requirement, the first part with a body and the first satisfy relation (\\ldots{{}}: "
               f"omitted lines). Whole models: {len(r.sysml_code_c0.splitlines())} and "
               f"{len(r.sysml_code_e1.splitlines())} lines.")
    tex = ("\\begin{figure*}[t]\n\\centering\n\\begin{minipage}[t]{0.48\\textwidth}\n"
           + listing(a, 1, "C0: minimal prompt") + "\n\\end{minipage}\\hfill\n\\begin{minipage}[t]{0.48\\textwidth}\n"
           + listing(b, 1, "E1: guided prompt") + "\n\\end{minipage}\n"
           + f"\\caption{{{caption}}}\n\\label{{fig:richness_example}}\n\\end{{figure*}}\n")
    (out / "fig_richness_example.tex").write_text(tex, encoding="utf-8")
    md = (f"## Richness example ({r.category}, run {r.run}, gpt-6-luna)\n\nC0 (minimal prompt):\n```\n{a}\n```\n"
          f"E1 (guided prompt):\n```\n{b}\n```")
    return tex, md


def main() -> None:
    out = out_dir("a12_paper_examples")
    _, md1 = repair_example(out)
    _, md2 = richness_example(out)
    write_md(out / "examples.md", "A12. Examples for the paper",
             ["Line numbers in the LaTeX listings are those of the stored files; the listings use the paper's "
              "`sysml` lstlisting style.", md1, md2])


if __name__ == "__main__":
    main()
